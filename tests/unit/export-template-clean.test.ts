interface TemplateScan {
  /** 수식이 아닌 숫자·날짜 셀 — 남아 있으면 금액·수량·참여율이다 (X-2 ①) */
  numericCells: string[];
  /** 계산값을 물고 있는 수식 셀 (X-2 ②) */
  cachedFormulaCells: string[];
  /** 남은 텍스트 셀 (X-2 ③) */
  textCells: TextCellLine[];
  /** 텍스트·빈칸·수식 어느 쪽도 아닌 셀. 불리언 등은 ①②③ 어디에도 걸리지 않아 따로 본다 */
  unexpectedCells: string[];
}

function scanTemplate(file: string): TemplateScan {
  // SheetJS .mjs 빌드의 readFile은 fs가 묶여 있지 않다 — readFileSync + read를 쓴다.
  // 수식·서식·표시형식을 모두 봐야 X-2 ①②를 판정할 수 있다
  const wb = XLSX.read(fs.readFileSync(file), {
    cellFormula: true,
    cellStyles: true,
    cellNF: true,
  });

  const scan: TemplateScan = {
    numericCells: [],
    cachedFormulaCells: [],
    textCells: [],
    unexpectedCells: [],
  };

  for (const sheetName of wb.SheetNames) {
    const ws = wb.Sheets[sheetName];
    if (!ws?.['!ref']) continue;
    const range = XLSX.utils.decode_range(ws['!ref']);
    for (let r = range.s.r; r <= range.e.r; r++) {
      for (let c = range.s.c; c <= range.e.c; c++) {
        const addr = XLSX.utils.encode_cell({ r, c });
        const cell = ws[addr] as XLSX.CellObject | undefined;
        if (!cell) continue;
        const at = `${sheetName}!${addr}`;

        if (cell.f) {
          // 값을 비운 수식 셀은 t='e'(계산값 없음)로 읽힌다. v가 살아 있으면 캐시가 남은 것
          if (cell.v !== undefined && cell.v !== null && cell.v !== '') {
            scan.cachedFormulaCells.push(`${at} = ${cell.f} → ${JSON.stringify(cell.v)}`);
          }
          continue;
        }

        switch (cell.t) {
          case 'n':
          case 'd':
            scan.numericCells.push(`${at} = ${JSON.stringify(cell.v)}`);
            break;
          case 's':
            scan.textCells.push(formatTextCell(sheetName, addr, cell.v));
            break;
          case 'z':
            break; // 서식만 남은 빈 셀 — 템플릿이 바로 이런 셀들로 이루어진다
          default:
            // 불리언('b')·수식 없는 에러('e') 등. 어느 검사에도 걸리지 않으므로 여기서 잡는다
            scan.unexpectedCells.push(`${at} (t=${cell.t}) = ${JSON.stringify(cell.v)}`);
        }
      }
    }
  }
  return scan;
}

function formatTextCell(sheet: string, addr: string, value: unknown): TextCellLine {
  return `${sheet}!${addr} = ${String(value)}`;
}

/**
 * 스냅샷 불일치 메시지. "다르다"만 알리면 새로 들어온 값이 데이터인지 라벨인지 알 수 없다 —
 * 늘어난 것·사라진 것을 **셀 주소와 함께** 보여 사람이 그 자리에서 판단하게 한다.
 */
function buildSnapshotFailureMessage(
  file: string,
  added: readonly string[],
  removed: readonly string[]
): string {
  const lines = [`[템플릿 정결성] ${file}의 텍스트 셀이 스냅샷과 다릅니다 (X-2 ③).`];
  if (added.length > 0) {
    lines.push(`  ▸ 새로 들어온 텍스트 ${added.length}개 — 성명·기관명·과제명 등 데이터인지 먼저 보십시오:`);
    for (const line of added) lines.push(`      + ${JSON.stringify(line)}`);
  }
  if (removed.length > 0) {
    lines.push(`  ▸ 사라진 텍스트 ${removed.length}개 — 서식 라벨이 지워졌는지 보십시오:`);
    for (const line of removed) lines.push(`      - ${JSON.stringify(line)}`);
  }
  lines.push(`  전부 구조 라벨이면 EXPECTED_TEXT_CELLS['${file}']를 그대로 갱신하십시오.`);
  lines.push('  하나라도 데이터면 템플릿을 커밋하지 마십시오 — 실예산·성명이 저장소에 남습니다.');
  return lines.join('\n');
}

